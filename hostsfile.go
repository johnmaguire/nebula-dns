package main

import (
	"bytes"
	"fmt"
	"net/netip"
	"os"
	"path/filepath"
	"slices"
	"strings"
)

// HostRecord is one DNS name and the addresses it resolves to.
type HostRecord struct {
	Name string
	IPs  []netip.Addr
}

const hostsFileHeader = "# Generated by nebula-dns from the Defined Networking API. Changes are overwritten.\n"

// RenderHostsFile formats records in hosts(5) format, one line per address.
// Output is sorted so an unchanged host list produces identical bytes.
func RenderHostsFile(records []HostRecord) []byte {
	sorted := slices.Clone(records)
	slices.SortFunc(sorted, func(a, b HostRecord) int { return strings.Compare(a.Name, b.Name) })

	var buf bytes.Buffer
	buf.WriteString(hostsFileHeader)
	for _, r := range sorted {
		ips := slices.Clone(r.IPs)
		slices.SortFunc(ips, netip.Addr.Compare)
		for _, ip := range ips {
			fmt.Fprintf(&buf, "%s %s\n", ip, r.Name)
		}
	}
	return buf.Bytes()
}

// WriteHostsFile replaces path with the rendered records and reports whether
// the contents changed. The file is swapped in by rename because resolvers
// re-read it on their own schedule, and a partial write would drop every name
// after the cut until the next run. Consumers in containers must therefore
// mount the directory, not the file: a single-file bind mount keeps the
// replaced inode.
func WriteHostsFile(path string, records []HostRecord) (bool, error) {
	content := RenderHostsFile(records)

	existing, err := os.ReadFile(path)
	if err == nil && bytes.Equal(existing, content) {
		return false, nil
	}
	if err != nil && !os.IsNotExist(err) {
		return false, fmt.Errorf("failed to read existing hosts file: %w", err)
	}

	tmp, err := os.CreateTemp(filepath.Dir(path), ".nebula-dns-*")
	if err != nil {
		return false, fmt.Errorf("failed to create temporary hosts file: %w", err)
	}
	defer os.Remove(tmp.Name())

	if _, err := tmp.Write(content); err != nil {
		tmp.Close()
		return false, fmt.Errorf("failed to write temporary hosts file: %w", err)
	}
	// CreateTemp creates 0600, and the resolver reading this usually runs as
	// a different user.
	if err := tmp.Chmod(0o644); err != nil {
		tmp.Close()
		return false, fmt.Errorf("failed to set hosts file mode: %w", err)
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return false, fmt.Errorf("failed to sync temporary hosts file: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return false, fmt.Errorf("failed to close temporary hosts file: %w", err)
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		return false, fmt.Errorf("failed to replace hosts file: %w", err)
	}
	return true, nil
}

// validHostname reports whether name can be written as a DNS name. A DN host
// name is free text, and in a hosts file a space or '#' would silently turn
// part of it into an alias or a comment.
func validHostname(name string) bool {
	if len(name) == 0 || len(name) > 253 {
		return false
	}
	for label := range strings.SplitSeq(name, ".") {
		if len(label) == 0 || len(label) > 63 {
			return false
		}
		for _, c := range label {
			if !(c >= 'a' && c <= 'z' || c >= '0' && c <= '9' || c == '-' || c == '_') {
				return false
			}
		}
	}
	return true
}
